import { plainToInstance } from 'class-transformer';
import { validate } from 'class-validator';
import { JwtService } from '@nestjs/jwt';
import { RefreshTokenDto } from './refresh-token.dto';

describe('RefreshTokenDto', () => {
  const errorsFor = async (refreshToken: unknown) =>
    validate(plainToInstance(RefreshTokenDto, { refreshToken }));

  it('should accept a refresh token generated by the API (JWT)', async () => {
    // Same kind of token AuthService.generateTokens returns
    const token = new JwtService().sign({ sub: 'user-id' }, { secret: 'test-refresh-secret', expiresIn: '7d' });

    expect(await errorsFor(token)).toHaveLength(0);
  });

  it.each([
    ['a UUID', '3f2b8c1e-9a4d-4e6b-8f1a-2c3d4e5f6a7b'],
    ['a random string', 'not-a-token'],
    ['an empty string', ''],
    ['a number', 123],
  ])('should reject %s', async (_label, value) => {
    expect((await errorsFor(value)).length).toBeGreaterThan(0);
  });
});
